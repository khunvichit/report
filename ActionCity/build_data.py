import json, math

def fmt(n, decimals=0):
    if n is None: return "—"
    v = round(float(n), decimals)
    if decimals == 0:
        return f"{int(v):,}"
    return f"{v:,.{decimals}f}"

def pct(n, decimals=1):
    return f"{round(float(n)*100, decimals):+.{decimals}f}%"

def gp_color(g):
    return "#c43b27" if float(g) < 50 else "#1f7a55"

def wow_color(v):
    return "#1f9d57" if float(v) >= 0 else "#d6453a"

def wow_arrow(v):
    return "▲" if float(v) >= 0 else "▼"

def stock_color(s):
    s = float(s)
    if s < 15: return "#c43b27"
    if s > 600: return "#b5740a"
    return "#2b2b33"

