# na_read logic: sold/recvd & on_hand-based
def arrival_read(sold, on_hand, launch_wk):
    # Simple heuristic
    if on_hand == 0: return "SOLD OUT", "#e3f5ec", "#1f9d57"
    weeks_since = 26 - launch_wk
    if weeks_since <= 1: return "JUST IN", "#eeedfe", "#5551FE"
    if on_hand < 10 and sold > on_hand * 2: return "HOT", "#fde8e8", "#c43b27"
    sell_rate = sold / max(weeks_since, 1)
    cover = on_hand / sell_rate if sell_rate > 0 else 99
    if cover > 12: return "OVERSTOCK", "#fbeecd", "#b5740a"
    if cover > 6:  return "SLOW", "#f5f5f5", "#8a8a93"
    if cover < 2:  return "HOT", "#fde8e8", "#c43b27"
    return "SELLING", "#e3f5ec", "#1f9d57"

