def arrival_read_badge(sold, stock, first_sale_wk):
    # HOT: very fast selling relative to stock
    ratio = sold / max(stock, 1)
    if ratio > 10 or (sold > 50 and stock < 20): return ("HOT",  "#1f9d57", "#ffffff")
    if ratio > 1.5 or sold > 30:                  return ("SELLING", "#e3f5ec", "#1f7a55")
    if sold < 5:                                   return ("JUST IN", "#E6E5FF", "#5551FE")
    return ("SELLING", "#e3f5ec", "#1f7a55")

