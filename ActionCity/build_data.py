def fmt(n, decimals=0):
    if n is None: return "—"
    if decimals == 0:
        return f"{int(round(n)):,}"
    return f"{round(n, decimals):,.{decimals}f}"

def pct(n):
    if n is None: return "—"
    sign = "+" if n >= 0 else ""
    return f"{sign}{round(n,1)}%"

